import { JointPose3D, MuscleGroupId } from "./AnatomicalModelBuilder";
import { DynamicPropType, Station3DType } from "./GymEquipmentBuilder";

export interface Exercise3DSpec {
  badge: string;
  primaryLabel: string;
  secondaryLabel: string;
  primaryMuscles: MuscleGroupId[];
  secondaryMuscles: MuscleGroupId[];
  station: Station3DType;
  prop: DynamicPropType;
  cameraPos: [number, number, number];
  cameraTarget: [number, number, number];
  poseStart: JointPose3D;
  poseEnd: JointPose3D;
}

function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}

function lerpVec3(
  a: [number, number, number],
  b: [number, number, number],
  t: number
): [number, number, number] {
  return [lerp(a[0], b[0], t), lerp(a[1], b[1], t), lerp(a[2], b[2], t)];
}

export function interpolateJointPose3D(
  s: JointPose3D,
  e: JointPose3D,
  t: number
): JointPose3D {
  return {
    rootPos: lerpVec3(s.rootPos, e.rootPos, t),
    rootRot: lerpVec3(s.rootRot, e.rootRot, t),
    spineRot: lerpVec3(s.spineRot, e.spineRot, t),
    headRot: lerpVec3(s.headRot, e.headRot, t),
    shoulderL: lerpVec3(s.shoulderL, e.shoulderL, t),
    shoulderR: lerpVec3(s.shoulderR, e.shoulderR, t),
    elbowL: lerpVec3(s.elbowL, e.elbowL, t),
    elbowR: lerpVec3(s.elbowR, e.elbowR, t),
    hipL: lerpVec3(s.hipL, e.hipL, t),
    hipR: lerpVec3(s.hipR, e.hipR, t),
    kneeL: lerpVec3(s.kneeL, e.kneeL, t),
    kneeR: lerpVec3(s.kneeR, e.kneeR, t),
    ankleL:
      s.ankleL && e.ankleL ? lerpVec3(s.ankleL, e.ankleL, t) : [0, 0, 0],
    ankleR:
      s.ankleR && e.ankleR ? lerpVec3(s.ankleR, e.ankleR, t) : [0, 0, 0],
  };
}

